#!/usr/bin/env python3
"""P12 support lane: generate publication_trainer_p12.py from the FROZEN P8 trainer.

The P12 protocol keeps the frozen P8 trainer semantics (every arm bootstrap,
render path, densification, camera sequence, eval) byte-identical and changes
ONLY the loss plumbing, so that the strong-baseline loss (P11-validated
fused-ssim, padding="same") is used instead of the frozen SepSSIM.

Exactly four anchored replacements are applied (each must match EXACTLY once):

  E1  import block        -> support-lane sys.path + `import p12_fused_loss as P12`
  E2  start of main()     -> `_P12_LOCK = P12.assert_and_log_lock(...)` (process start)
  E3  loss factory        -> `ssim_fn = P12.P12FusedSSIM(device="cuda")`
  E4  results dict        -> `"fused_loss_lock": _P12_LOCK,`

The frozen `SepSSIM` class is intentionally left in the file byte-identical as
the P11 reference implementation (it is simply no longer instantiated).
No renderer, model, optimizer, densification or camera-sequence code changes.

Writes the generated trainer plus a patch report (input sha256, output sha256,
each hunk with its exact matched text and occurrence count).
"""
import argparse
import hashlib
import json
import os
import sys
import time

FROZEN_P8_TRAINER_SHA256 = (
    "f67b2125f93b84c9afee103675c13dbca301aa58f385069b5e853d6272a20618")

BANNER = """\
# ============================================================================
# GENERATED by p12_make_trainer.py from the FROZEN P8 trainer sha256
# {sha}
# (source: {src})
# P12 support-lane derivative: EXACTLY the four anchored edits recorded in
# {report} -- loss plumbing only; no renderer/model/optimizer/densification/
# camera-sequence change. The SepSSIM class body below is kept byte-identical
# as the P11 reference implementation (no longer instantiated).
# ============================================================================
"""

HUNKS = [
    {
        "name": "E1_import_support_lane",
        "old": """import numpy as np
import torch
import torch.nn.functional as F

# ---------------------------------------------------------------- paths
""",
        "new": """import numpy as np
import torch
import torch.nn.functional as F

# ---- P12 support lane: P11-validated fused-SSIM loss plumbing (loss
# plumbing only; NO algorithm change; the frozen SepSSIM class below is
# retained byte-identical as the P11 reference implementation) ----
sys.path.insert(0, "/root/epic05_p12_support")
import p12_fused_loss as P12  # noqa: E402

# ---------------------------------------------------------------- paths
""",
    },
    {
        "name": "E2_runtime_lock_process_start",
        "old": """    os.environ.setdefault("CUDA_VISIBLE_DEVICES", str(args.gpu))
    seed_val = args.seed if args.seed is not None else 42
    torch.manual_seed(seed_val)
    np.random.seed(seed_val)
    random.seed(seed_val)

""",
        "new": """    os.environ.setdefault("CUDA_VISIBLE_DEVICES", str(args.gpu))
    seed_val = args.seed if args.seed is not None else 42
    torch.manual_seed(seed_val)
    np.random.seed(seed_val)
    random.seed(seed_val)

    # P12 fused-loss runtime identity lock (required by the P12 protocol):
    # asserts the P11-validated fused-ssim identity and logs one
    # `P12_FUSED_LOSS_LOCK {json}` line at process start. Raises
    # BLOCKED_FUSED_LOSS_IDENTITY on any mismatch.
    _P12_LOCK = P12.assert_and_log_lock(context={
        "arm": args.arm, "scene": args.scene, "iterations": args.iterations,
        "seed": seed_val, "gpu": args.gpu})

""",
    },
    {
        "name": "E3_loss_factory",
        "old": "    ssim_fn = SepSSIM(device=\"cuda\")\n",
        "new": ("    # P12: P11-validated fused-ssim (padding=\"same\"); SepSSIM above is\n"
                "    # the frozen reference implementation, no longer instantiated.\n"
                "    ssim_fn = P12.P12FusedSSIM(device=\"cuda\")\n"),
    },
    {
        "name": "E4_results_lock_record",
        "old": '        "binary_identity": ident,\n',
        "new": '        "binary_identity": ident,\n        "fused_loss_lock": _P12_LOCK,\n',
    },
]


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="frozen publication_trainer_p8.py")
    ap.add_argument("--output", required=True, help="generated publication_trainer_p12.py")
    ap.add_argument("--report", required=True, help="patch report JSON")
    ap.add_argument("--expected-sha256", default=FROZEN_P8_TRAINER_SHA256)
    args = ap.parse_args()

    in_sha = sha256_file(args.input)
    if args.expected_sha256 and in_sha != args.expected_sha256:
        print(json.dumps({"status": "BLOCKED_INPUT_SHA_MISMATCH",
                          "expected": args.expected_sha256, "actual": in_sha}))
        sys.exit(2)

    with open(args.input, "r", encoding="utf-8", newline="") as f:
        text = f.read()

    applied = []
    for h in HUNKS:
        n = text.count(h["old"])
        if n != 1:
            print(json.dumps({"status": "BLOCKED_ANCHOR",
                              "hunk": h["name"], "occurrences": n}))
            sys.exit(3)
        text = text.replace(h["old"], h["new"], 1)
        applied.append({"hunk": h["name"], "occurrences_matched": 1,
                        "old": h["old"], "new": h["new"]})

    banner = BANNER.format(sha=in_sha, src=os.path.abspath(args.input),
                           report=os.path.abspath(args.report))
    lines = text.split("\n", 1)
    text = lines[0] + "\n" + banner + (lines[1] if len(lines) > 1 else "")

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="") as f:
        f.write(text)

    # syntax check the generated file
    import py_compile
    try:
        py_compile.compile(args.output, doraise=True)
        syntax_ok = True
    except py_compile.PyCompileError as e:
        syntax_ok = False
        print(json.dumps({"status": "BLOCKED_GENERATED_SYNTAX_ERROR",
                          "error": str(e)}))
        sys.exit(4)

    report = {
        "phase": "P12 support lane - trainer generation (frozen P8 -> P12 loss plumbing)",
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "input": {"path": os.path.abspath(args.input), "sha256": in_sha},
        "output": {"path": os.path.abspath(args.output),
                   "sha256": sha256_file(args.output),
                   "bytes": os.path.getsize(args.output)},
        "syntax_ok": syntax_ok,
        "n_hunks": len(applied),
        "hunks": applied,
        "separation_of_concerns": {
            "changed": "loss plumbing only (fused-SSIM factory + runtime lock + "
                       "results record)",
            "unchanged": ["all bootstrap_* functions", "arm definitions / env switches",
                          "render_with_meta (both renderer call paths)",
                          "SepSSIM class body (kept as frozen reference)",
                          "GaussianModel / optimizer / densification / camera sequence",
                          "evaluation / artifact writers"],
        },
    }
    with open(args.report, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    print(json.dumps({"status": "OK", "input_sha256": in_sha,
                      "output_sha256": report["output"]["sha256"],
                      "n_hunks": len(applied)}, indent=2))


if __name__ == "__main__":
    main()
