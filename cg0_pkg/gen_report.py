L.append("All four checkpoint SHA256 hashes resolve against the N1 canonical provenance;")
L.append("the three frozen binary pins match the packet SHA256s exactly.")
L.append("")
L.append("## 3. Oracle boundary / no-leakage (prereg sections 3-4)")
L.append("")
L.append("The compiler consumes ONLY: oracle expected depth maps (COMPILE64), GT training images,")
L.append("calibration cameras, and the scalar source Gaussian count N_source. It does NOT read")
L.append("source xyz/covariance/opacity/SH/optimizer moments/per-Gaussian IDs/RGB.")
L.append("`CG0_NO_LEAKAGE_AUDIT.json` records `source_gaussian_params_read_by_compiler=false` for all cells.")
L.append("")
L.append("## 4. Per-cell results")
