L.append("|------|:---:|:---:|:---:|:---:|")
for c in cells:
    cr=s(c,"count_ratio"); cf=tm(c,"conditional_compile_refine_fraction")
    c0=g(c,"compiled0","holdout16","psnr"); c15=g(c,"compiled1500","holdout16","psnr")
    L.append("| %s | %s (%.3f) | %s (%.3f) | %s (%+.2f) | %s (%+.2f) |"%(
        c, "PASS" if 0.8<=cr<=1.2 else "FAIL", cr, "PASS" if cf<=0.12 else "FAIL", cf,
        "PASS" if c0>=-1.5 else "FAIL", c0, "PASS" if c15>=-0.15 else "FAIL", c15))
