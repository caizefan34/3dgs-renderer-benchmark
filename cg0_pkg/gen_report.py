import json, os, hashlib, datetime
os.chdir("/root/epic05_cg0/out")
cells=["room@15000","room@25000","bicycle@15000","bicycle@25000"]
verdict=json.load(open("CG0_VERDICT.json"))
ident=json.load(open("CG0_SOURCE_IDENTITY.json"))
def g(c,*ks):
    d=json.load(open(c+"/CG0_QUITY.json"))
    for k in ks: d=d[k]
    return d
def s(c,k): return json.load(open(c+"/CG0_SUMMARY.json"))[k]
def st(c,k): return json.load(open(c+"/CG0_COMPILER_STATS.json"))[k]
def tm(c,k): return json.load(open(c+"/CG0_TIMING.json"))[k]

L=[]
L.append("# CG0 Report - Gaussian-as-Compiled-Representation Oracle")
L.append("")
L.append("**Verdict: `%s`**"%verdict["verdict"])
L.append("")
L.append("Generated: %s (EPIC-05 A100, authoritative frozen binaries)"%datetime.datetime.now().strftime("%Y-%m-%d %H:%M"))
L.append("")
L.append("## 1. Central question")
L.append("")
L.append("CG0 isolates whether a deployable Gaussian scene can be *compiled* deterministically")
L.append("from an oracle geometry signal (expected depth from an authoritative C0 checkpoint)")
L.append("plus ground-truth RGB, followed by a short topology-frozen C0 refinement (0-1500 steps),")
L.append("instead of long-form optimization. All thresholds are frozen in `CG0_PREREG.md`; the")
L.append("analyzer (`cg0_analyze.py`) owns the verdict and no post-hoc rescue is permitted.")
